# -*- coding: utf-8 -*-
"""
StratumRO — Computer Vision Engine Contracts (Phase 2)
Dedicated contracts for optical image segmentation (Meta SAM 2, ONNX DirectML).
Completely decoupled from LLM chat and text generation architectures.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, List, Optional, Protocol, Tuple, runtime_checkable
import numpy as np


class VisionPromptType(str, Enum):
    BOUNDING_BOX = "BOUNDING_BOX"
    POSITIVE_POINT = "POSITIVE_POINT"
    NEGATIVE_POINT = "NEGATIVE_POINT"
    MULTI_POINT = "MULTI_POINT"
    PRIOR_MASK = "PRIOR_MASK"


@dataclass
class VisionPrompt:
    """
    Input spatial prompt passed to the vision segmentation engine.
    Coordinates are in pixel space relative to the input image patch.
    """
    prompt_type: VisionPromptType
    box: Optional[Tuple[float, float, float, float]] = None  # (min_x, min_y, max_x, max_y)
    points: List[Tuple[float, float]] = field(default_factory=list)
    point_labels: List[int] = field(default_factory=list)   # 1 = positive, 0 = negative
    mask_input: Optional[np.ndarray] = None


@dataclass
class VisionMaskResult:
    """
    Raw output generated by the vision segmentation engine.
    """
    binary_mask: np.ndarray        # 2D boolean array (H, W)
    iou_prediction: float          # Model confidence score [0.0, 1.0]
    raw_logits: Optional[np.ndarray] = None
    inference_time_ms: float = 0.0


@runtime_checkable
class IVisionEngine(Protocol):
    """
    Contract for Local Computer Vision segmentation inference engines.
    """
    @property
    def engine_name(self) -> str:
        """Name of the engine (e.g. 'SAM2_Hiera_Tiny', 'ONNX_DirectML')."""
        ...

    @property
    def is_local(self) -> bool:
        """Indicates if inference executes entirely on-premises / air-gapped."""
        ...

    def load_model(self, model_path: str, device: str = "cpu") -> bool:
        """Loads weights and initializes inference session."""
        ...

    def set_image(self, image_rgb: np.ndarray) -> None:
        """Computes or caches image embeddings."""
        ...

    def predict_mask(self, prompt: VisionPrompt) -> VisionMaskResult:
        """Executes mask decoder with the given spatial prompt."""
        ...
